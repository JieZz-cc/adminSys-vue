package com.itheima.Api;

public class MathDemo {
    public static void main(String[] args) {
        Math.abs(88.1);         // 绝对值
        Math.ceil(1.1);         // 向上取整
        Math.floor(1.02);       //向下取整
        Math.max(1,2);          // 比较
        Math.pow(1.1,1.2);      // 1.1的1.2次幂
        Math.random();          // 返回double，[0.0, 1.0)
        System.out.println(Math.round(1.5));
        System.out.println(Math.round(-1.5));

    }
}
